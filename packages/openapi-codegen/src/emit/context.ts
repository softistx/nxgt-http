import type { Diagnostic } from '../errors';
import type {
	ApiIR,
	LiteralNode,
	MediaIR,
	NamedSchema,
	ObjectNode,
	OperationIR,
	Property,
	SchemaNode,
} from '../ir/types';
import { checkNames } from './collisions';
import { findLoosened } from './loosened';
import type { EmitOptions, ObjectMode } from './options';

/** A property whose default the validator fills in: optional going in, present coming out. */
export const appliesDefault = (property: Property): boolean =>
	!property.required && property.schema.default !== undefined;

/** The IR plus what both emitters need to agree on. */
export class EmitContext {
	readonly ir: ApiIR;
	readonly options: EmitOptions;
	readonly #byId: Map<string, NamedSchema>;
	/** Schemas whose validator accepts something other than what it returns. */
	readonly #inputs = new Set<string>();
	/** With `dates: 'date'`, schemas whose values hold a `Date`. */
	readonly #dated = new Set<string>();
	/** What the generated code accepts but the spec would refuse. */
	readonly warnings: Diagnostic[] = [];
	/** While set, every name `typeName` gives out, for a file that imports them. */
	#typeUses: Set<string> | undefined;

	constructor(ir: ApiIR, options: EmitOptions) {
		this.ir = ir;
		this.options = options;
		this.#byId = new Map(ir.schemas.map((schema) => [schema.id, schema]));
		this.#fixpoint(this.#dated, (node) => this.datesIn(node));
		this.#fixpoint(this.#inputs, (node) => this.inputDiffers(node));
		this.warnings.push(...findLoosened(this));
		checkNames(this);
	}

	get header(): string {
		return `// Generated by @nxgt/openapi-codegen from ${this.options.source}. Do not edit.`;
	}

	schema(id: string): NamedSchema {
		const schema = this.#byId.get(id);
		if (!schema) throw new Error(`openapi-codegen: no schema ${id}`);
		return schema;
	}

	/** Whether the schema needs a separate `XInput` type. */
	hasInput(id: string): boolean {
		return this.#inputs.has(id);
	}

	/** `Employee`, or `EmployeeInput` on the input side when the two differ. */
	typeName(id: string, input: boolean): string {
		const { name } = this.schema(id);
		const out = input && this.#inputs.has(id) ? `${name}Input` : name;
		this.#typeUses?.add(out);
		return out;
	}

	/**
	 * The node of a named schema printed as an `as const` object: an `enum` of
	 * two or more strings or numbers. `z.enum()` takes no booleans, and a
	 * single value is a constant, not a choice.
	 */
	enumOf(id: string): LiteralNode | undefined {
		if (this.options.enums !== 'object') return undefined;
		const { node } = this.schema(id);
		return node.kind === 'literal' &&
			node.values.length > 1 &&
			node.values.every(
				(value) => typeof value === 'string' || typeof value === 'number',
			)
			? node
			: undefined;
	}

	/**
	 * The operation's form body, when its fields can be read from text: an
	 * object with no `allOf` parent and no schema for extra keys. It gets a
	 * validator of its own, `z<Operation>Form`.
	 */
	formOf(
		operation: OperationIR,
	): { media: MediaIR; object: ObjectNode } | undefined {
		const media = operation.body?.content.find((m) => m.kind === 'form');
		if (!media?.schema || media.schema.nullable) return undefined;
		const object = this.resolve(media.schema);
		return object.kind === 'object' &&
			!object.nullable &&
			object.extends.length === 0 &&
			typeof object.additional !== 'object'
			? { media, object }
			: undefined;
	}

	/** Runs `print`, and returns what it printed and every type name it used. */
	collectTypes<T>(print: () => T): { value: T; names: Set<string> } {
		const outer = this.#typeUses;
		const names = new Set<string>();
		this.#typeUses = names;
		try {
			return { value: print(), names };
		} finally {
			this.#typeUses = outer;
		}
	}

	resolve(node: SchemaNode): SchemaNode {
		let current = node;
		for (let hops = 0; current.kind === 'ref' && hops < 64; hops++) {
			current = this.schema(current.target).node;
		}
		return current;
	}

	/**
	 * The object's unknown-key mode. An intersection member keeps its own: a
	 * Zod intersection reports an unknown key only when every member does.
	 */
	mode(node: ObjectNode): ObjectMode {
		return node.additional === 'default'
			? this.options.unknownKeys
			: node.additional;
	}

	/** The mode of a named object schema. */
	modeOf(id: string): ObjectMode {
		const node = this.resolve(this.schema(id).node);
		return node.kind === 'object' ? this.mode(node) : 'strip';
	}

	/** A property of `object`, its own or one it extends. */
	propertyOf(
		object: ObjectNode,
		name: string,
		seen = new Set<string>(),
	): Property | undefined {
		const own = object.properties.find((p) => p.name === name);
		if (own) return own;
		for (const id of object.extends) {
			if (seen.has(id)) continue;
			seen.add(id);
			const parent = this.resolve(this.schema(id).node);
			if (parent.kind !== 'object') continue;
			const found = this.propertyOf(parent, name, seen);
			if (found) return found;
		}
		return undefined;
	}

	/**
	 * Whether the node's validator is a `ZodObject`, which `.extend()` and
	 * `discriminatedUnion` need. A recursive schema is typed `ZodType`, and an
	 * object built on one is an intersection.
	 */
	isZodObject(node: SchemaNode): boolean {
		if (node.nullable) return false;
		if (node.kind === 'ref') {
			const schema = this.schema(node.target);
			return !schema.recursive && this.isZodObject(schema.node);
		}
		return (
			node.kind === 'object' &&
			node.extends.every((target) => this.isZodObject({ kind: 'ref', target }))
		);
	}

	/** A `date-time` that the validator decodes to a `Date`: with `dates: 'date'` only. */
	isDate(node: SchemaNode): boolean {
		return (
			this.options.dates === 'date' &&
			node.kind === 'string' &&
			node.format === 'date-time'
		);
	}

	/** Whether a value of the node holds a decoded `Date`, anywhere inside. */
	datesIn(node: SchemaNode): boolean {
		switch (node.kind) {
			case 'string':
				return this.isDate(node);
			case 'ref':
				return this.#dated.has(node.target);
			case 'array':
				return this.datesIn(node.items);
			case 'record':
				return this.datesIn(node.values);
			case 'union':
				return node.variants.some((variant) => this.datesIn(variant));
			case 'intersection':
				return node.members.some((member) => this.datesIn(member));
			case 'object':
				return (
					node.extends.some((id) => this.#dated.has(id)) ||
					node.properties.some((p) => this.datesIn(p.schema)) ||
					(typeof node.additional === 'object' &&
						this.datesIn(node.additional.schema))
				);
			default:
				return false;
		}
	}

	/**
	 * `text`, the type of `node`, as JSON carries it: `Wire<T>` when it holds a
	 * `Date`, which travels as its ISO string. Replies and `paths.ts`
	 * responses are typed this way; only a decoded value holds a `Date`.
	 */
	wire(node: SchemaNode, text: string): string {
		if (!this.datesIn(node)) return text;
		this.#typeUses?.add('Wire');
		return `Wire<${text}>`;
	}

	/** Whether the node's validator accepts something other than what it returns. */
	inputDiffers(node: SchemaNode): boolean {
		switch (node.kind) {
			case 'string':
				// A codec takes the string and returns the Date.
				return this.isDate(node);
			case 'ref':
				return this.#inputs.has(node.target);
			case 'array':
				return this.inputDiffers(node.items);
			case 'record':
				return this.inputDiffers(node.values);
			case 'union':
				return node.variants.some((variant) => this.inputDiffers(variant));
			case 'intersection':
				return node.members.some((member) => this.inputDiffers(member));
			case 'object':
				return (
					node.extends.some((id) => this.#inputs.has(id)) ||
					node.properties.some(
						(p) => appliesDefault(p) || this.inputDiffers(p.schema),
					) ||
					(typeof node.additional === 'object' &&
						this.inputDiffers(node.additional.schema))
				);
			default:
				return false;
		}
	}

	/** The schemas whose node `holds`, to a fixpoint, since schemas can reach each other in cycles. */
	#fixpoint(set: Set<string>, holds: (node: SchemaNode) => boolean): void {
		let changed = true;
		while (changed) {
			changed = false;
			for (const schema of this.ir.schemas) {
				if (set.has(schema.id) || !holds(schema.node)) continue;
				set.add(schema.id);
				changed = true;
			}
		}
	}
}

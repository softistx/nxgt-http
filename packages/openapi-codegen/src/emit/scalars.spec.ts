/** `scalars: 'exact'`: a string scalar of @nxgt/typespec as the schema of @nxgt/zod. */
import { describe, expect, it } from 'bun:test';
import { operations } from '../../test/generated/scalars/operations';
import * as Z from '../../test/generated/scalars/zod';
import { generateFiles } from '../generate';
import { createMemoryFileSystem } from '../loader/fs';

const input = new URL(
	'../../test/fixtures/scalars/openapi.yaml',
	import.meta.url,
).pathname;

/** The fixture's files by name, generated with `scalars` as given. */
async function generated(scalars?: 'pattern' | 'exact') {
	const { files } = await generateFiles({
		input,
		output: '/out',
		hono: true,
		alxia: true,
		importExtension: '.js',
		...(scalars === undefined ? {} : { scalars }),
	});
	return Object.fromEntries(
		files.map((f) => [f.path.split('/').pop(), f.content]),
	);
}

/** The generated header names the spec by a path of this machine. */
const withoutHeader = (content: string | undefined): string =>
	(content ?? '').replace(/^\/\/ Generated by .*\n/, '');

/** `zod.ts` of a spec with just these schemas. */
async function zodOf(
	schemas: Record<string, unknown>,
	scalars: 'pattern' | 'exact',
) {
	const fs = createMemoryFileSystem({
		'/s/openapi.json': JSON.stringify({
			openapi: '3.1.0',
			info: { title: 't', version: '1' },
			paths: {},
			components: { schemas },
		}),
	});
	const { files, warnings } = await generateFiles(
		{ input: '/s/openapi.json', output: '/out', scalars },
		{ fs },
	);
	const zod = files.find((f) => f.path.endsWith('/zod.ts'))?.content ?? '';
	return { zod, warnings };
}

const ok = (
	schema: { safeParse(v: unknown): { success: boolean } },
	value: unknown,
) => schema.safeParse(value).success;

describe('scalars: pattern', () => {
	it('is the default, byte for byte', async () => {
		expect(await generated('pattern')).toEqual(await generated());
	});

	it('checks a scalar by its pattern and imports nothing of @nxgt/zod', async () => {
		const files = await generated('pattern');
		for (const [name, content] of Object.entries(files)) {
			expect(content, name).not.toContain('@nxgt/zod');
		}
		expect(files['zod.ts']).toContain(
			'export const zIBAN = z.string().regex(/^[A-Z]{2}\\d{2}[A-Z0-9]{1,30}$/u);',
		);
		expect(withoutHeader(files['zod.ts'])).toMatchSnapshot('pattern/zod.ts');
	});
});

describe('scalars: exact', () => {
	it('prints the schema of @nxgt/zod, imported by name where it is used', async () => {
		const files = await generated('exact');
		expect(files['zod.ts']).toContain(
			'export const zIBAN = ibanSchema.check(z.regex(/^[A-Z]{2}\\d{2}[A-Z0-9]{1,30}$/u));',
		);
		expect(files['zod.ts']).toContain(
			"import { emailAddressSchema, emojiSchema, ibanSchema, ipSchema, uuidSchema } from '@nxgt/zod';",
		);
		expect(files['operations.ts']).toContain(
			"import { emailAddressSchema } from '@nxgt/zod';",
		);
		expect(files['alxia.ts']).toContain(
			"import { emailAddressSchema } from '@nxgt/zod';",
		);
		expect(files['types.ts']).not.toContain('@nxgt/zod');
		expect(withoutHeader(files['zod.ts'])).toMatchSnapshot('exact/zod.ts');
	});

	it('adds the bounds of the spec as checks, which every schema takes', async () => {
		const { 'zod.ts': zod } = await generated('exact');
		expect(zod).toContain(
			"bounded: ibanSchema.check(z.minLength(15, 'Too small: expected string to have >=15 characters'), z.maxLength(24, 'Too big: expected string to have <=24 characters')).check(z.regex(/^[A-Z]{2}\\d{2}[A-Z0-9]{1,30}$/u)).optional()",
		);
		expect(zod).toContain(
			"ipSchema.check(z.maxLength(45, 'Too big: expected string to have <=45 characters')).nullable()",
		);
	});

	it('keeps the pattern of the spec on top of the scalar, so a narrowed scalar stays narrow', () => {
		const be = 'BE68539007547034';
		const fr = 'FR1420041010050500013M02606';
		// A plain scalar checks its canonical pattern too, redundantly.
		expect(ok(Z.zIBAN, fr)).toBe(true);
		expect(ok(Z.zIBAN, be)).toBe(true);
		// FrIban: x-nxgt-scalar IBAN, narrowed to ^FR.
		expect(ok(Z.zFrIban, fr)).toBe(true);
		expect(ok(Z.zFrIban, be)).toBe(false);
	});

	it('leaves a codec and an unknown scalar to their pattern', async () => {
		const { 'zod.ts': zod } = await generated('exact');
		expect(zod).toContain(
			'export const zDateTime = z.iso.datetime({ offset: true }).regex(',
		);
		expect(zod).toContain('legacy: z.string().regex(/^L-\\d+$/u).optional()');
	});

	it('validates with the schemas, bounds included', () => {
		const iban = 'FR7630006000011234567890189';
		expect(ok(Z.zIBAN, iban)).toBe(true);
		expect(ok(Z.zIBAN, 'FR76')).toBe(false);
		const account = {
			id: '123e4567-e89b-12d3-a456-426614174000',
			iban,
			openedAt: '2024-03-10T10:00:00Z',
		};
		expect(ok(Z.zAccount, account)).toBe(true);
		expect(ok(Z.zAccount, { ...account, id: 'nope' })).toBe(false);
		expect(ok(Z.zAccount, { ...account, bounded: iban })).toBe(false);
		expect(ok(Z.zAccount, { ...account, bounded: 'BE68539007547034' })).toBe(
			true,
		);
		expect(ok(Z.zAccount, { ...account, lastIp: null })).toBe(true);
		expect(ok(Z.zAccount, { ...account, lastIp: '10.0.0.1' })).toBe(true);
		expect(ok(Z.zAccount, { ...account, lastIp: '10.0.0.999' })).toBe(false);
		expect(ok(Z.zAccount, { ...account, mood: '🙂' })).toBe(true);
		expect(ok(Z.zAccount, { ...account, mood: 'happy' })).toBe(false);
	});

	it('validates an inline parameter with its bound', () => {
		const { query } = operations.listAccounts;
		expect(ok(query, { owner: 'a@b.co' })).toBe(true);
		expect(ok(query, { owner: `${'a'.repeat(250)}@b.co` })).toBe(false);
		expect(ok(query, { owner: 'not an email' })).toBe(false);
	});
});

describe('the zod import of zod.ts', () => {
	const iban = { type: 'string', 'x-nxgt-scalar': 'IBAN' };

	it('is left out when no schema calls z, which noUnusedLocals would refuse', async () => {
		const { zod } = await zodOf({ Iban: iban }, 'exact');
		expect(zod).not.toContain("from 'zod'");
		expect(zod).toContain("import { ibanSchema } from '@nxgt/zod';");
		expect(zod).toContain('export const zIban = ibanSchema;');
	});

	it('is not decided by a doc comment that says "z."', async () => {
		const description = 'Sorted x, y, z. Then z.string() is not called.';
		const { zod } = await zodOf({ Iban: { ...iban, description } }, 'exact');
		expect(zod).toContain(description);
		expect(zod).not.toContain("from 'zod'");
		const pattern = await zodOf({ Iban: { ...iban, description } }, 'pattern');
		expect(pattern.zod).toContain("import { z } from 'zod';");
	});

	it('is there when a bound is added, or another schema calls z', async () => {
		const bounded = await zodOf({ Iban: { ...iban, maxLength: 24 } }, 'exact');
		expect(bounded.zod).toContain("import { z } from 'zod';");
		const mixed = await zodOf(
			{ Iban: iban, Pet: { type: 'object', properties: {} } },
			'exact',
		);
		expect(mixed.zod).toContain("import { z } from 'zod';");
	});

	it('is there for an enum and for a recursive schema', async () => {
		const { zod } = await zodOf(
			{ Iban: iban, Kind: { enum: ['a', 'b'] } },
			'exact',
		);
		expect(zod).toContain("import { z } from 'zod';");
	});
});

describe('an x-nxgt-scalar that is not on a string', () => {
	const schemas = {
		Count: { type: 'integer', 'x-nxgt-scalar': 'PositiveInt', minimum: 1 },
		Odd: { type: 'string', 'x-nxgt-scalar': 5 },
	};

	it('is no string scalar: nothing changes with exact, and no warning', async () => {
		const exact = await zodOf(schemas, 'exact');
		const pattern = await zodOf(schemas, 'pattern');
		expect(exact.zod).toBe(pattern.zod);
		expect(exact.zod).toContain('export const zCount = z.int().min(1);');
		expect(exact.zod).toContain('export const zOdd = z.string();');
		expect(exact.warnings).toEqual([]);
	});
});
